// ------------------------------------------------------
// backend/scripts/migrate-reservation-headers.js
// ------------------------------------------------------
// Replaces the old flat matWhReservations (single item+store+qty row, no
// project header) with matWhReservationHeaders + matWhReservationItems, per
// direct request: a reservation now covers multiple items for one project.
// Safe to re-run -- checks before every DROP/ALTER/CREATE.
//
// matWhReservations had 0 real rows when this was written (confirmed live,
// the feature hadn't shipped yet), so this drops it outright rather than
// migrating rows that don't exist -- if that's no longer true when this
// runs, STOP and write a real data migration instead of re-running this.
import { sequelizeUtf8 } from "../config/db.js";
import { MatWhReservationHeader } from "../models/MatWhReservationHeader.js";
import { MatWhReservationItem } from "../models/MatWhReservationItem.js";

async function columnExists(table, column) {
    const [rows] = await sequelizeUtf8.query(`
        SELECT COLUMN_NAME FROM INFORMATION_SCHEMA.COLUMNS
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = :table AND COLUMN_NAME = :column
    `, { replacements: { table, column } });
    return rows.length > 0;
}

async function tableExists(table) {
    const [rows] = await sequelizeUtf8.query(`
        SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES
        WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = :table
    `, { replacements: { table } });
    return rows.length > 0;
}

const run = async () => {
    try {
        if (await tableExists('matWhReservations')) {
            const [[{ n }]] = await sequelizeUtf8.query('SELECT COUNT(*) AS n FROM `matWhReservations`');
            if (n > 0) {
                throw new Error(`matWhReservations has ${n} real rows -- refusing to drop, write a data migration instead`);
            }
            await sequelizeUtf8.query('DROP TABLE `matWhReservations`');
            console.log('✅ Dropped old matWhReservations (0 rows)');
        } else {
            console.log('⏭️  matWhReservations already gone, skipping drop');
        }

        await MatWhReservationHeader.sync();
        console.log('✅ matWhReservationHeaders ready');
        await MatWhReservationItem.sync();
        console.log('✅ matWhReservationItems ready');

        if (!(await columnExists('matWhPurchaseOrders', 'isAutoGenerated'))) {
            await sequelizeUtf8.query("ALTER TABLE `matWhPurchaseOrders` ADD COLUMN `isAutoGenerated` TINYINT(1) NOT NULL DEFAULT 0");
            console.log('✅ Added matWhPurchaseOrders.isAutoGenerated');
        } else {
            console.log('⏭️  matWhPurchaseOrders.isAutoGenerated already exists, skipping');
        }
        // vendorId was NOT NULL -- loosen it so an auto-generated PO for an
        // item with no preferredVendorId can be created with vendor unset.
        await sequelizeUtf8.query("ALTER TABLE `matWhPurchaseOrders` MODIFY COLUMN `vendorId` INT NULL");
        console.log('✅ matWhPurchaseOrders.vendorId is nullable');

        if (!(await columnExists('matWhPurchaseOrderItems', 'reservationItemId'))) {
            await sequelizeUtf8.query("ALTER TABLE `matWhPurchaseOrderItems` ADD COLUMN `reservationItemId` INT NULL");
            console.log('✅ Added matWhPurchaseOrderItems.reservationItemId');
        } else {
            console.log('⏭️  matWhPurchaseOrderItems.reservationItemId already exists, skipping');
        }
        await sequelizeUtf8.query("ALTER TABLE `matWhPurchaseOrderItems` MODIFY COLUMN `unitPrice` FLOAT NOT NULL DEFAULT 0");
        await sequelizeUtf8.query("ALTER TABLE `matWhPurchaseOrderItems` MODIFY COLUMN `lineAmt` FLOAT NOT NULL DEFAULT 0");
        console.log('✅ matWhPurchaseOrderItems.unitPrice/lineAmt default to 0');

        process.exit(0);
    } catch (err) {
        console.error('❌ Migration failed:', err);
        process.exit(1);
    }
};

run();
